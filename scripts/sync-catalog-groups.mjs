#!/usr/bin/env node
// Regenerates src/check/catalog-groups.ts from the public https://16kb.dev/api/catalog.
// Only exact Maven group names that the catalog itself lists are written.
import { writeFileSync } from "node:fs";

const res = await fetch("https://16kb.dev/api/catalog", { headers: { Accept: "application/json" } });
if (!res.ok) throw new Error(`catalog fetch failed: ${res.status}`);
const { entries } = await res.json();
const groups = new Set();
for (const e of entries) {
  for (const c of e.mavenCoords || []) {
    const i = c.lastIndexOf(":");
    if (i <= 0) continue;
    const g = c.slice(0, i).trim().toLowerCase();
    if (!g || g.includes("*")) continue;
    if (g.includes("jitpack") || g === "com.example" || g.startsWith("com.example.")) continue;
    groups.add(g);
  }
}
const list = [...groups].sort();
const out = `// Generated by scripts/sync-catalog-groups.mjs from https://16kb.dev/api/catalog on ${new Date().toISOString().slice(0, 10)}.
// Exact public Maven groups listed in the 16kb.dev catalog. Do not edit by hand.
export const CATALOG_GROUPS: readonly string[] = ${JSON.stringify(list, null, 2)};
`;
writeFileSync(new URL("../src/check/catalog-groups.ts", import.meta.url), out);
console.log(`Wrote ${list.length} groups.`);
